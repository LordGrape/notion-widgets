/* FIRAC is independently deployed; distribute the shared operating context. */
import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile(new URL('../widget-platform.js', import.meta.url), 'utf8');
const target = new URL('../firac-reader/site/widget-platform.js', import.meta.url);
const output = '/* Generated by tools/build-widget-platform.mjs. Edit root widget-platform.js. */\n' + source;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('FIRAC platform asset is stale. Run node tools/build-widget-platform.mjs.');
} else await writeFile(target, output);
console.log('Shared operating context verified.');
