/* FIRAC is deployed independently. Distribute the canonical shared UI asset. */
import {readFile, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const source = await readFile(new URL('../widget-icons.js', import.meta.url), 'utf8');
const target = new URL('../firac-reader/site/widget-icons.js', import.meta.url);
const output = '/* Generated by tools/build-widget-icons.mjs. Edit root widget-icons.js. */\n' + source;
if (process.argv.includes('--check')) {
 if (await readFile(target, 'utf8') !== output) throw new Error('FIRAC icon asset is stale. Run node tools/build-widget-icons.mjs.');
} else await writeFile(target, output);
console.log('Shared FIRAC icon asset verified: ' + fileURLToPath(target));
